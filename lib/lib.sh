# lib.sh: helper functions shared by the driver scripts and the generated job scripts.

# Sample name for this array task: line SLURM_ARRAY_TASK_ID of SAMPLE_LIST.
sample_for_task() {
  local name
  name=$(sed -n "${SLURM_ARRAY_TASK_ID}p" "${SAMPLE_LIST}")
  if [ -z "${name}" ]; then
    echo "ERROR: no line ${SLURM_ARRAY_TASK_ID} in ${SAMPLE_LIST}" >&2
    return 1
  fi
  echo "${name}"
}

# First line of every log: which sample and job this log belongs to.
log_header() {
  local who=${JOB_LABEL:-${SAMPLE}}
  if [ -n "${SLURM_ARRAY_TASK_ID:-}" ]; then
    who=$(sample_for_task)
  fi
  echo "Executing on sample: ${who}"
  echo "Job: ${SLURM_JOB_NAME:-none} (${SLURM_JOB_ID:-no job id}) on ${SLURMD_NODENAME:-$(hostname)}"
  if [ -n "${SLURM_ARRAY_TASK_ID:-}" ]; then
    echo "Array job ${SLURM_ARRAY_JOB_ID}, task ${SLURM_ARRAY_TASK_ID}"
  fi
  echo "Started: $(date '+%F %T')"
}

# Print a header line before each stage so logs are easy to scan.
log_step() {
  echo
  echo "=== $(date '+%F %T') | ${SAMPLE} | $* ==="
}

# Same as log_step, but names the job (a sample, or a batch of samples) instead of the current sample.
log_job_step() {
  echo
  echo "=== $(date '+%F %T') | ${JOB_LABEL:-${SAMPLE}} | $* ==="
}

# Load modules and say so in the log.
do_module() {
  log_step "module load $*"
  module load "$@"
}

# Stop early if a required variable is empty.
require_vars() {
  local name
  for name in "$@"; do
    if [ -z "${!name:-}" ]; then
      echo "ERROR: ${name} is not set. Check config/config.env." >&2
      return 1
    fi
  done
}

# Write a uniform sbatch script and print its path.
# Usage: create_sbatch NAME CPUS MEM TIME COMMAND [EXTRA_SBATCH_LINES]
#   NAME     short step name; the script and its log are named ${SAMPLE}_NAME
#   COMMAND  a function from steps.sh, with its arguments
create_sbatch() {
  local name=$1 cpus=$2 mem=$3 time=$4 command=$5 extra=${6:-}
  local label=${JOB_LABEL:-${SAMPLE}}   # sample name, or a batch name for multi-sample jobs
  local id_pattern=${LOG_ID_PATTERN:-%j}   # %j for one job, %A_%a for an array
  local script=${SBATCH_DIR}/${label}_${name}.sbatch

  mkdir -p "${SBATCH_DIR}" "${LOG_DIR}"   # the log folder must exist before submission

  cat > "${script}" <<SBATCH_EOF
#!/bin/bash
# ${name} for ${label}. Generated by create_sbatch in lib/lib.sh; edit there, not here.
#SBATCH --job-name=${label}_${name}
#SBATCH --output=${LOG_DIR}/${label}_${name}_${id_pattern}.out
#SBATCH --cpus-per-task=${cpus}
#SBATCH --mem=${mem}
#SBATCH --time=${time}
${extra}

set -eo pipefail
export JOB_LABEL=${label}
source ${PROJECT_DIR}/config/config.env
source ${PROJECT_DIR}/lib/lib.sh
source ${PROJECT_DIR}/lib/steps.sh
set_sample "${SAMPLE}"

log_header
log_job_step "start ${name} (cpus=\${SLURM_CPUS_PER_TASK} mem=\${SLURM_MEM_PER_NODE}M)"
${command}
log_job_step "finished ${name}"
SBATCH_EOF

  echo "${script}"
}

# Submit a script and print its job ID. Optional second argument: a job ID to wait for.
submit_job() {
  local script=$1 dependency=${2:-}
  local args=(--parsable)

  if [ -n "${dependency}" ]; then
    args+=(--dependency=afterok:"${dependency}")
  fi

  sbatch "${args[@]}" "${script}"
}

# Create and submit in one call. Prints the job ID.
# Usage: create_and_submit NAME CPUS MEM TIME COMMAND [DEPENDENCY_JOB_ID] [EXTRA_SBATCH_LINES]
create_and_submit() {
  local name=$1 cpus=$2 mem=$3 time=$4 command=$5 dependency=${6:-} extra=${7:-}
  local script
  script=$(create_sbatch "${name}" "${cpus}" "${mem}" "${time}" "${command}" "${extra}")
  submit_job "${script}" "${dependency}"
}
